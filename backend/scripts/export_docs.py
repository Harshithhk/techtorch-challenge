"""Regenerate the architecture artifacts from the code: OpenAPI schema and the agent graph.

Run from backend/:  PYTHONPATH=. uv run python scripts/export_docs.py
Writes into ../docs/architecture/. Nothing here is hand-written, so the files cannot drift from the code.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path
from unittest.mock import MagicMock

from langgraph.checkpoint.memory import InMemorySaver

from app.agent.graph import build_graph
from app.agent.nodes import AgentDeps
from app.main import create_app
from app.settings import get_settings
from app.storage.sandbox import SandboxStore

OUT = Path(__file__).resolve().parents[2] / "docs" / "architecture"


def export_openapi() -> Path:
    """Write the OpenAPI schema as JSON. Output: path of the written file."""
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "openapi.json"
    path.write_text(json.dumps(create_app(get_settings()).openapi(), indent=2) + "\n", encoding="utf-8")
    return path


def export_graph() -> Path:
    """Write the compiled agent graph as Mermaid (renders on GitHub) and ASCII (for terminals)."""
    llm = MagicMock()
    llm.bind_tools.return_value = llm
    deps = AgentDeps(llm=llm, load_ledger=lambda: None, sandbox=SandboxStore(Path("/nonexistent")),
                     term_months=12, default_as_of=date(2025, 12, 31))
    graph = build_graph(deps, InMemorySaver()).get_graph()
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "agent_graph.md"
    path.write_text(
        "# Agent graph\n\n"
        "Generated by `backend/scripts/export_docs.py` from the compiled LangGraph. Do not edit by hand.\n\n"
        "## Mermaid\n\n```mermaid\n" + graph.draw_mermaid() + "\n```\n\n"
        "## ASCII\n\n```text\n" + graph.draw_ascii() + "\n```\n",
        encoding="utf-8",
    )
    return path


if __name__ == "__main__":
    print(export_openapi())
    print(export_graph())
